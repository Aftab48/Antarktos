type Fixture = (typeof fixtures)[number]

const findExisting = async (fx: Fixture) => {
  const where: Where = fx.collection === 'reports' ? { title: { equals: (fx.data as Doc).title } } : { source_url: { equals: fx.data.source_url } }
  return (await payload.find({ collection: fx.collection, where, locale: 'en', depth: 0, limit: 1 })).docs[0]?.id as number | undefined
}

