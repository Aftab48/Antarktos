const ids: Record<string, number> = {}
const uploaded: string[] = []
for (const fx of fixtures) {
  const existing = await findExisting(fx)
  if (existing) {
    ids[fx.key] = existing
    continue
  }
  const buffer: Buffer = 'buffer' in fx && fx.buffer ? fx.buffer : readFileSync((fx as Doc).file)
  const form = new FormData()
  form.append('file', new Blob([new Uint8Array(buffer)], { type: fx.mimeType }), 'name' in fx ? fx.name : path.basename(fx.file))
  form.append('_payload', JSON.stringify(fx.data))
  ids[fx.key] = (await rest(editor, 'POST', `/api/${fx.collection}?draft=true`, form)).doc.id
  uploaded.push(`${fx.key} (${buffer.length} bytes)`)
}
console.log(uploaded.length ? `uploaded: ${uploaded.join(', ')}` : 'all test records already exist, nothing uploaded')

const docs: Record<string, Doc> = {}
