await step('re-running processed records calls no LLM and keeps chunk ids (citations stay valid)', async () => {
  const before = (await chunksOf('reports', isea.id)).map((c) => c.id)
  const records: [string, Doc][] = [['reports', isea], ['reports', scanned], ...photos.map((p): [string, Doc] => ['media', p])]
  for (const [collection, d] of records) {
    const r = await processRecord(payload, collection, d.id)
    assert.equal(r.error, undefined)
    assert.equal(r.llm.length, 0, `${collection}/${d.id} called an LLM`)
    assert.equal(r.state, d.processing_state)
  }
  assert.deepEqual((await chunksOf('reports', isea.id)).map((c) => c.id), before)
})

await step('a stale admin form cannot wipe AI output or the state; a real edit clears ai_generated', async () => {
  const url = `/api/reports/${isea.id}?draft=true`
  await rest(editor, 'PATCH', url, { summary: '', keywords: [], processing_state: 'queued', page_count: null })
  let d = await latest('reports', isea.id)
  assert.equal(d.summary.en, isea.summary.en)
  assert.deepEqual(d.keywords, isea.keywords)
  assert.deepEqual([d.processing_state, d.page_count, d.ai_generated], ['ready', 13, true])
  await rest(editor, 'PATCH', url, { keywords: [...isea.keywords, 'edited by staff'] })
  d = await latest('reports', isea.id)
  assert.equal(d.ai_generated, false)
  // Put the test record back through the pipeline's own write path.
  await payload.update({ collection: 'reports', id: isea.id, draft: true, data: { keywords: isea.keywords, ai_generated: true }, context: { pipeline: true } })
})

await step('publish / unpublish re-index; a pending draft keeps the record out of public search', async () => {
  const flags = async () => (await db(sql`select bool_and(published) as every, bool_or(published) as some from archive_chunks where collection = 'reports' and doc_id = ${String(isea.id)}`))[0]
  const url = `/api/reports/${isea.id}`
  await rest(reviewer, 'PATCH', url, { _status: 'published' })
  await until('chunks published', async () => (await flags()).every === true, 60_000)
  await rest(editor, 'PATCH', `${url}?draft=true`, { credit: isea.credit })
  await until('pending draft hides chunks', async () => (await flags()).some === false, 60_000)
  await rest(reviewer, 'PATCH', url, { _status: 'published' })
  await until('chunks published again', async () => (await flags()).every === true, 60_000)
  await rest(reviewer, 'PATCH', url, { _status: 'draft' })
  await until('unpublish hides chunks', async () => (await flags()).some === false, 60_000)
})

await step('a metadata-only event is indexed as one chunk per locale; deleting it removes them', async () => {
  const { doc } = await rest(editor, 'POST', '/api/events?draft=true', {
    title: 'Step 3 check event',
    description: 'Polar science outreach talk for school students in Goa.',
    event_type: 'school_outreach',
    location: 'Goa',
  })
  try {
    await until('event ready', async () => (await latest('events', doc.id)).processing_state === 'ready', 60_000)
    let chunks = await chunksOf('events', doc.id)
    assert.deepEqual(chunks.map((c) => [c.locale, c.position, c.heading]), [['en', 0, 'Step 3 check event']])
    await rest(editor, 'PATCH', `/api/events/${doc.id}?draft=true&locale=hi`, { title: 'चरण 3 जाँच कार्यक्रम', description: 'गोवा में स्कूली छात्रों के लिए ध्रुवीय विज्ञान वार्ता।' })
    chunks = (await until('Hindi chunk', async () => ((await chunksOf('events', doc.id)).length === 2 ? chunksOf('events', doc.id) : undefined), 60_000)) as Doc[]
    assert.deepEqual(chunks.map((c) => c.locale), ['en', 'hi'])
    assert.match(chunks[1].text, /ध्रुवीय/)
  } finally {
    await rest(editor, 'DELETE', `/api/events/${doc.id}`)
  }
  assert.equal((await chunksOf('events', doc.id)).length, 0)
})

