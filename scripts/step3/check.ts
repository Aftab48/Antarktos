// An A4 page that is only a JPEG, like a scan: no text layer at all.
async function scannedPdf(): Promise<Buffer> {
  const lines = ['SCIENTIFIC REPORT (SCANNED PAGE)', 'Step 3 test page: this text is part of an image.', 'There is no text layer, so the pipeline must', 'flag the file as needs_ocr and not summarise it.']
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1240" height="1754"><rect width="100%" height="100%" fill="#f3efe4"/>${lines
    .map((l, i) => `<text x="110" y="${220 + i * 70}" font-family="serif" font-size="40" fill="#2a2a2a">${l}</text>`)
    .join('')}</svg>`
  const jpeg = await sharp(Buffer.from(svg)).jpeg({ quality: 60 }).toBuffer()
  const parts: Buffer[] = []
  const offsets: number[] = []
  let size = 0
  const push = (b: Buffer | string) => {
    const buf = typeof b === 'string' ? Buffer.from(b, 'latin1') : b
    parts.push(buf)
    size += buf.length
  }
  const obj = (n: number, dict: string, stream?: Buffer) => {
    offsets[n] = size
    push(`${n} 0 obj\n${dict}\n`)
    if (stream) {
      push('stream\n')
      push(stream)
      push('\nendstream\n')
    }
    push('endobj\n')
  }
  const content = Buffer.from('q 595 0 0 842 0 0 cm /Im0 Do Q')
  push('%PDF-1.4\n')
  obj(1, '<</Type/Catalog/Pages 2 0 R>>')
  obj(2, '<</Type/Pages/Kids[3 0 R]/Count 1>>')
  obj(3, '<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 842]/Resources<</XObject<</Im0 4 0 R>>>>/Contents 5 0 R>>')
  obj(4, `<</Type/XObject/Subtype/Image/Width 1240/Height 1754/ColorSpace/DeviceRGB/BitsPerComponent 8/Filter/DCTDecode/Length ${jpeg.length}>>`, jpeg)
  obj(5, `<</Length ${content.length}>>`, content)
  const xref = size
  push(`xref\n0 6\n0000000000 65535 f \n${offsets.slice(1).map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`)
  push(`trailer<</Size 6/Root 1 0 R>>\nstartxref\n${xref}\n%%EOF\n`)
  return Buffer.concat(parts)
}

